"""ROS 2/DDS peer transport without a central application service.

The domain applications use :class:`Envelope` as their in-process command DTO.
On the wire, ``elesim_interfaces/PeerEnvelope`` is a bounded DDS carrier.
Discovery is an application announcement/heartbeat mesh; no participant
forwards traffic for another participant.

All ROS imports are deliberately lazy.  Importing ``elesim_protocol`` therefore
continues to work in release/build tooling that is not running inside a sourced
ROS environment.
"""

